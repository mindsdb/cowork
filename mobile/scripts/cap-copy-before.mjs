// `capacitor:copy:before` hook: runs on every `cap copy` / `cap sync`.
//
// 1. www/offline.html: generated from offline.template.html with the remote
//    URL its "Try again" reloads, from COWORK_ENV (staging | prod, default
//    staging). Keep the URL table identical to env.ts, which
//    capacitor.config.ts reads.
// 2. ios/App/Version.xcconfig: MARKETING_VERSION from package.json and
//    CURRENT_PROJECT_VERSION from COWORK_BUILD_NUMBER (default 1). Android
//    reads the same two inputs directly in android/app/build.gradle.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const URLS = {
  prod: 'https://cowork.mindshub.ai',
  staging: 'https://cowork.staging.mindshub.ai',
};

const raw = (process.env.COWORK_ENV ?? '').trim().toLowerCase();
const env = raw === '' || raw === 'staging' ? 'staging' : raw === 'prod' || raw === 'production' ? 'prod' : null;
if (!env) {
  console.error(`COWORK_ENV must be "staging" or "prod", got "${process.env.COWORK_ENV}"`);
  process.exit(1);
}
// The URL is written into the page itself, never read from a sibling file:
// with server.url set, Capacitor Android serves only the error page locally,
// so a separate script would fail to load and the page could not know its URL.
const PLACEHOLDER = '__COWORK_REMOTE_URL__';
const template = readFileSync(join(root, 'offline.template.html'), 'utf8');
if (template.split(PLACEHOLDER).length !== 2) {
  console.error(`offline.template.html must contain ${PLACEHOLDER} exactly once`);
  process.exit(1);
}
writeFileSync(join(root, 'www', 'offline.html'), template.replace(PLACEHOLDER, URLS[env]));
console.log(`[mobile] COWORK_ENV=${env} -> ${URLS[env]}`);

const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
if (!/^\d+\.\d+\.\d+$/.test(version)) {
  console.error(`package.json version must be MAJOR.MINOR.PATCH for the stores, got "${version}"`);
  process.exit(1);
}
const build = (process.env.COWORK_BUILD_NUMBER ?? '').trim() || '1';
if (!/^\d+$/.test(build)) {
  console.error(`COWORK_BUILD_NUMBER must be a positive integer, got "${build}"`);
  process.exit(1);
}
const xcconfig = join(root, 'ios', 'App', 'Version.xcconfig');
if (existsSync(dirname(xcconfig))) {
  writeFileSync(
    xcconfig,
    '// Generated by scripts/cap-copy-before.mjs from package.json and\n' +
      '// COWORK_BUILD_NUMBER on every cap copy/sync. Do not edit by hand.\n' +
      `MARKETING_VERSION = ${version}\n` +
      `CURRENT_PROJECT_VERSION = ${build}\n`,
  );
  console.log(`[mobile] iOS version ${version} (${build})`);
}
